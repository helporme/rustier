//! Cargo manifest rendering for a generated shim crate.

use std::path::Path;

use crate::compiler::{codegen::fragment::FragmentPrint, db::Db, inputs::Platform};

/// Package metadata and the source dependency used by the generated shim.
pub struct ManifestOpts<'a> {
    /// Source package name. The generated package is named `cursed-{name}`.
    pub name: &'a str,
    /// Version of the generated package.
    pub version: &'a str,
    /// Rust edition of the generated package.
    pub edition: &'a str,
    /// Dependency name used to refer to the source crate in generated Rust.
    pub source_crate_name: &'a str,
    /// Source package directory, absolute or relative to the generated
    /// manifest.
    pub source_package_path: &'a Path,
}

/// Renders a `Cargo.toml` for the shim using the platform configured in `db`.
///
/// The caller must write the shim to `src/lib.rs`. For platforms where
/// [`Platform::build_script_body`] returns `Some`, the caller must also write
/// `build.rs` with that body inside `fn main()`.
///
/// This only renders the manifest; it does not write files or configure a
/// parent workspace. `Platform` must have been set in the database before
/// calling.
pub fn render_manifest(db: &dyn Db, opts: ManifestOpts<'_>) -> String {
    let platform = Platform::get(db);
    let build = if platform.needs_build_script() {
        "build = \"build.rs\"\n"
    } else {
        ""
    };
    let dependencies = platform.manifest_deps().print();
    let build_dependencies = platform.manifest_build_deps().print();

    format!(
        "# @generated by rust-curse. Do not edit manually.\n\n\
         [package]\n\
         name = {}\n\
         version = {}\n\
         edition = {}\n\
         publish = false\n\
         {build}\n\
         [lib]\n\
         crate-type = [\"cdylib\", \"rlib\"]\n\n\
         [dependencies]\n\
         {} = {{ package = {}, path = {} }}\n\
         {dependencies}{build_dependencies}\n",
        toml_string(&format!("cursed-{}", opts.name)),
        toml_string(opts.version),
        toml_string(opts.edition),
        toml_string(opts.source_crate_name),
        toml_string(opts.name),
        toml_string(opts.source_package_path.to_string_lossy().as_ref()),
    )
}

fn toml_string(value: &str) -> String {
    let mut escaped = String::from("\"");
    for ch in value.chars() {
        match ch {
            '"' => escaped.push_str("\\\""),
            '\\' => escaped.push_str("\\\\"),
            '\u{0}'..='\u{1f}' | '\u{7f}' => {
                use std::fmt::Write;
                write!(escaped, "\\u{:04X}", ch as u32).unwrap();
            }
            _ => escaped.push(ch),
        }
    }
    escaped.push('"');
    escaped
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::compiler::{db::RootDatabase, inputs::WasmEnv};

    fn render(db: &dyn Db) -> String {
        render_manifest(
            db,
            ManifestOpts {
                name: "source-package",
                version: "1.2.3",
                edition: "2024",
                source_crate_name: "source_crate",
                source_package_path: Path::new("../source"),
            },
        )
    }

    #[test]
    fn node_manifest() {
        let mut db = RootDatabase::default();
        Platform::set(&mut db, Platform::Node);
        assert_eq!(
            render(&db),
            concat!(
                "# @generated by rust-curse. Do not edit manually.\n\n",
                "[package]\n",
                "name = \"cursed-source-package\"\n",
                "version = \"1.2.3\"\n",
                "edition = \"2024\"\n",
                "publish = false\n",
                "build = \"build.rs\"\n\n",
                "[lib]\n",
                "crate-type = [\"cdylib\", \"rlib\"]\n\n",
                "[dependencies]\n",
                "\"source_crate\" = { package = \"source-package\", path = \"../source\" }\n",
                "napi = { version = \"3\", features = [\"napi10\"] }\n",
                "napi-derive = { version = \"3\" }\n\n",
                "[build-dependencies]\n",
                "napi-build = \"2\"\n",
            )
        );
    }

    #[test]
    fn wasm_manifests_follow_database_platform() {
        let mut db = RootDatabase::default();
        Platform::set(&mut db, Platform::Node);
        assert!(render(&db).contains("napi"));
        for target in [WasmEnv::Web, WasmEnv::Node] {
            Platform::set(&mut db, Platform::Wasm { target });
            let manifest = render(&db);
            assert!(manifest.contains("crate-type = [\"cdylib\", \"rlib\"]"));
            assert!(manifest.ends_with("wasm-bindgen = \"0.2\"\n"));
            assert!(!manifest.contains("napi"));
            assert!(!manifest.contains("build"));
        }
    }

    #[test]
    fn escapes_toml_strings() {
        assert_eq!(
            toml_string("C:\\a\"b\n\r\t\u{0}\u{7f}/日本語"),
            "\"C:\\\\a\\\"b\\u000A\\u000D\\u0009\\u0000\\u007F/日本語\"",
        );
    }
}
