//! A module that defines types used for binding compilation.

use crate::{
    codegen::{
        api::Api,
        cast::DirectCastRule,
        db::Db,
        fragment::FragmentOnce,
        ir::type_::{Primitive, Type},
    },
    frag,
};

/// A type that is accepted by source code.
#[derive(Copy, Clone, Debug, PartialEq, Eq, Hash, salsa::Update)]
pub struct SourceType<'db> {
    /// Inner ir type that can be mapped to the source type.
    pub value: Type<'db>,
    /// Access mode used to pass the value.
    pub mode: PassMode,
}

/// Specifies a way to pass a value.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, salsa::Update)]
pub enum PassMode {
    Ref,
    Mut,
    Owned,
}

/// A type that is passed across the boundary.
// todo: rename to "boundary type" with all occurences in code
#[derive(Copy, Clone, Debug, PartialEq, Eq, Hash)]
pub struct BindingsType<'db> {
    /// The fully qualified name of the bindings type as generated by the
    /// codegen.
    pub fqn: &'db str,
}

/// JavaScript type, sometimes passed by generated bindings across the boundary.
/// Actual runtime type is specified by [`crate::codegen::api::Api::js_type`]
#[derive(Copy, Clone, Debug, PartialEq, Eq, Hash, salsa::Update)]
pub struct JsType;

/// A rule to cast an owned source type to a reference source type.
pub struct CastOwnedTypeToRefTypeRule;

impl<'db> DirectCastRule<'db, SourceType<'db>, SourceType<'db>> for CastOwnedTypeToRefTypeRule {
    fn predecessor(self, _db: &'db dyn Db, to: SourceType<'db>) -> Option<SourceType<'db>> {
        if to.mode == PassMode::Ref {
            Some(SourceType {
                value: to.value,
                mode: PassMode::Owned,
            })
        } else {
            None
        }
    }

    fn compile(
        self,
        _db: &'db dyn Db,
        _from: SourceType<'db>,
        _to: SourceType<'db>,
        in_expr: impl FragmentOnce + 'db,
    ) -> impl FragmentOnce + 'db {
        frag!(&{ in_expr })
    }
}

/// A rule to cast an owned source type to a mutable source type.
pub struct CastOwnedTypeToMutTypeRule;

impl<'db> DirectCastRule<'db, SourceType<'db>, SourceType<'db>> for CastOwnedTypeToMutTypeRule {
    fn predecessor(self, _db: &'db dyn Db, to: SourceType<'db>) -> Option<SourceType<'db>> {
        if to.mode == PassMode::Mut {
            Some(SourceType {
                value: to.value,
                mode: PassMode::Owned,
            })
        } else {
            None
        }
    }

    fn compile(
        self,
        _db: &'db dyn Db,
        _from: SourceType<'db>,
        _to: SourceType<'db>,
        in_expr: impl FragmentOnce + 'db,
    ) -> impl FragmentOnce + 'db {
        frag!(&mut { in_expr })
    }
}

impl<'db> Type<'db> {
    /// Gets the type into a [source type][SourceType] with the default
    /// [`PassMode::Owned`].
    pub fn source_type(self) -> SourceType<'db> {
        SourceType {
            value: self,
            // by default all types are passed as owned values
            mode: PassMode::Owned,
        }
    }

    /// Gets the fully qualified name of the type used as a boundary-in type.
    pub fn boundary_in_fqn_name(self, db: &'db dyn Db) -> &'db str {
        let api = Api::get(db);

        match self {
            Type::Primitive(_) | Type::String | Type::Str => api.js_type(db),
            Type::Struct(id) => id.binding_name(db),
            Type::Enum(id) => id.binding_name(db),
        }
    }

    /// Gets the fully qualified name of the type used as a boundary-out type.
    pub fn boundary_out_fqn_name(self, db: &'db dyn Db) -> &'db str {
        match self {
            Type::Primitive(Primitive::Boolean) => "bool",
            Type::Primitive(Primitive::i8) => "i8",
            Type::Primitive(Primitive::u8) => "u8",
            Type::Primitive(Primitive::i16) => "i16",
            Type::Primitive(Primitive::u16) => "u16",
            Type::Primitive(Primitive::i32) => "i32",
            Type::Primitive(Primitive::u32) | Type::Primitive(Primitive::Char) => "u32",
            Type::Primitive(Primitive::f64) | Type::Primitive(Primitive::f32) => "f64",
            Type::String => "String",
            Type::Struct(id) => id.binding_name(db),
            Type::Enum(id) => id.binding_name(db),
            Type::Str => unreachable!("str cannot be returned from the function"),
        }
    }
}
