//! Install and run the NAPI-RS CLI for native Node.js bindings.

use std::{
    fs,
    path::{Path, PathBuf},
    process::{Command, Output},
};

use miette::Diagnostic;
use thiserror::Error;

const NAPI_CLI_PACKAGE: &str = "@napi-rs/cli@3.7.2";
const NAPI_CLI_BIN: &str = "napi";
const GENERATED_JS_FILE: &str = "index.js";

/// Options for installing the local NAPI CLI tool.
pub struct EnsureNapiCliInstalledOpts<'a> {
    /// Directory where npm should install `@napi-rs/cli`.
    pub install_root_path: &'a Path,
}

/// Options for building a crate into a native Node.js binding.
pub struct BuildOpts<'a> {
    /// Path to the crate directory used as the NAPI CLI working directory.
    pub project_root_path: &'a Path,
    /// Directory where the NAPI CLI should write generated files.
    pub out_dir_path: &'a Path,
    /// Path to the local `napi` executable.
    pub node_cli_path: &'a Path,
    /// Whether to build with `napi build --release`.
    pub release: bool,
}

/// Files generated by the NAPI CLI.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct BuildOutput {
    /// Path to the generated native Node.js addon.
    pub node_path: PathBuf,
    /// Path to the generated JavaScript binding file.
    pub js_path: PathBuf,
}

/// Ensure a local NAPI CLI is installed under `install_root_path`.
///
/// Returns the path to the installed `napi` binary.
///
/// ```no_run
/// use rust_curse::tools::node::{ensure_napi_cli_installed, EnsureNapiCliInstalledOpts};
/// use std::path::Path;
///
/// let napi = ensure_napi_cli_installed(EnsureNapiCliInstalledOpts {
///     install_root_path: Path::new("/tmp/rust-curse-tools"),
/// })?;
/// # let _ = napi;
/// # Ok::<(), rust_curse::tools::node::EnsureNapiCliInstalledError>(())
/// ```
pub fn ensure_napi_cli_installed(
    opts: EnsureNapiCliInstalledOpts<'_>,
) -> Result<PathBuf, EnsureNapiCliInstalledError> {
    fs::create_dir_all(opts.install_root_path).map_err(|source| {
        EnsureNapiCliInstalledError::CreateInstallRoot {
            path: opts.install_root_path.to_path_buf(),
            source,
        }
    })?;

    let napi_bin_name = if cfg!(windows) {
        format!("{NAPI_CLI_BIN}.cmd")
    } else {
        NAPI_CLI_BIN.to_string()
    };
    let tool_bin_path = opts
        .install_root_path
        .join("node_modules")
        .join(".bin")
        .join(napi_bin_name);

    if tool_bin_path.is_file() {
        let check = Command::new(&tool_bin_path)
            .arg("--version")
            .output()
            .map_err(|source| EnsureNapiCliInstalledError::CheckCli {
                path: tool_bin_path.clone(),
                source,
            })?;

        if check.status.success() {
            return Ok(tool_bin_path);
        }
    }

    let output = Command::new("npm")
        .args([
            "install",
            "--ignore-scripts",
            "--save-dev",
            NAPI_CLI_PACKAGE,
        ])
        .current_dir(opts.install_root_path)
        .output()
        .map_err(|source| EnsureNapiCliInstalledError::InstallCli { source })?;

    ensure_success(
        &output,
        &format!(
            "`npm install --ignore-scripts --save-dev {NAPI_CLI_PACKAGE}` failed in {}",
            opts.install_root_path.display()
        ),
    )
    .map_err(|source| EnsureNapiCliInstalledError::InstallCliFailed { source })?;

    if !tool_bin_path.is_file() {
        return Err(EnsureNapiCliInstalledError::MissingInstalledCli {
            path: tool_bin_path,
        });
    }

    let check = Command::new(&tool_bin_path)
        .arg("--version")
        .output()
        .map_err(|source| EnsureNapiCliInstalledError::CheckCli {
            path: tool_bin_path.clone(),
            source,
        })?;

    ensure_success(
        &check,
        &format!(
            "installed NAPI CLI at {} failed `--version`",
            tool_bin_path.display()
        ),
    )
    .map_err(|source| EnsureNapiCliInstalledError::InstalledCliCheckFailed { source })?;

    Ok(tool_bin_path)
}

/// Build a crate with the NAPI CLI and generate native Node.js bindings.
///
/// `project_root_path` is used as the working directory for `napi build`. The
/// build must produce exactly one `.node` artifact in `out_dir_path`.
///
/// ```no_run
/// use rust_curse::tools::node::{build, BuildOpts};
/// use std::path::Path;
///
/// let output = build(BuildOpts {
///     project_root_path: Path::new("/path/to/crate"),
///     out_dir_path: Path::new("/path/to/out"),
///     node_cli_path: Path::new("/path/to/napi"),
///     release: true,
/// })?;
/// # let _ = output;
/// # Ok::<(), rust_curse::tools::node::BuildError>(())
/// ```
pub fn build(opts: BuildOpts<'_>) -> Result<BuildOutput, BuildError> {
    fs::create_dir_all(opts.out_dir_path).map_err(|source| BuildError::CreateOutputDir {
        path: opts.out_dir_path.to_path_buf(),
        source,
    })?;

    let manifest_path = opts.project_root_path.join("Cargo.toml");
    let mut build = Command::new(opts.node_cli_path);
    build
        .arg("build")
        .arg("--manifest-path")
        .arg(&manifest_path)
        .arg("--output-dir")
        .arg(opts.out_dir_path)
        .arg("--platform")
        .arg("--esm")
        .arg("--js")
        .arg(GENERATED_JS_FILE)
        .current_dir(opts.project_root_path);
    if opts.release {
        build.arg("--release");
    }

    let output = build.output().map_err(|source| BuildError::RunNapiCli {
        path: opts.node_cli_path.to_path_buf(),
        source,
    })?;

    ensure_success(
        &output,
        &format!(
            "`{} build --manifest-path {}` failed",
            opts.node_cli_path.display(),
            manifest_path.display()
        ),
    )
    .map_err(|source| BuildError::NapiCliFailed { source })?;

    let js_path = opts.out_dir_path.join(GENERATED_JS_FILE);
    if !js_path.is_file() {
        return Err(BuildError::MissingGeneratedJs { path: js_path });
    }

    let node_path = built_node_artifact(opts.out_dir_path)?;

    Ok(BuildOutput { node_path, js_path })
}

fn built_node_artifact(out_dir_path: &Path) -> Result<PathBuf, BuildError> {
    let mut node_paths = Vec::new();

    for entry in fs::read_dir(out_dir_path).map_err(|source| BuildError::ReadOutputDir {
        path: out_dir_path.to_path_buf(),
        source,
    })? {
        let entry = entry.map_err(|source| BuildError::ReadOutputDir {
            path: out_dir_path.to_path_buf(),
            source,
        })?;
        let path = entry.path();
        if path.extension().and_then(|ext| ext.to_str()) == Some("node") {
            node_paths.push(path);
        }
    }

    node_paths.sort();

    match node_paths.len() {
        0 => Err(BuildError::MissingGeneratedNode {
            out_dir_path: out_dir_path.to_path_buf(),
        }),
        1 => Ok(node_paths.remove(0)),
        _ => {
            let artifacts = node_paths
                .iter()
                .map(|path| format!("  - {}", path.display()))
                .collect::<Vec<_>>()
                .join("\n");
            Err(BuildError::AmbiguousGeneratedNode { artifacts })
        }
    }
}

fn ensure_success(output: &Output, context: &str) -> Result<(), CommandFailed> {
    if output.status.success() {
        return Ok(());
    }

    Err(CommandFailed {
        context: context.to_string(),
        exit_code: output.status.code(),
        stdout: String::from_utf8_lossy(&output.stdout)
            .trim_end()
            .to_string(),
        stderr: String::from_utf8_lossy(&output.stderr)
            .trim_end()
            .to_string(),
    })
}

/// A command exited with a non-zero status.
#[derive(Error, Diagnostic, Debug)]
#[error("{context} (exit code {exit_code:?})\nstdout:\n{stdout}\nstderr:\n{stderr}")]
#[diagnostic(code(rust_curse::node::command_failed))]
pub struct CommandFailed {
    context: String,
    exit_code: Option<i32>,
    stdout: String,
    stderr: String,
}

/// Errors that can happen while ensuring the local NAPI CLI is installed.
#[derive(Error, Diagnostic, Debug)]
pub enum EnsureNapiCliInstalledError {
    #[error("failed to create NAPI CLI install root at {}", path.display())]
    #[diagnostic(code(rust_curse::node::create_install_root))]
    CreateInstallRoot {
        path: PathBuf,
        #[source]
        source: std::io::Error,
    },

    #[error("failed to run NAPI CLI at {}", path.display())]
    #[diagnostic(code(rust_curse::node::check_cli))]
    CheckCli {
        path: PathBuf,
        #[source]
        source: std::io::Error,
    },

    #[error("failed to run `npm install --ignore-scripts --save-dev {NAPI_CLI_PACKAGE}`")]
    #[diagnostic(code(rust_curse::node::install_cli))]
    InstallCli {
        #[source]
        source: std::io::Error,
    },

    #[error("{source}")]
    #[diagnostic(code(rust_curse::node::install_cli_failed))]
    InstallCliFailed {
        #[source]
        source: CommandFailed,
    },

    #[error("`npm install --ignore-scripts --save-dev {NAPI_CLI_PACKAGE}` completed but did not create {}", path.display())]
    #[diagnostic(code(rust_curse::node::missing_installed_cli))]
    MissingInstalledCli { path: PathBuf },

    #[error("{source}")]
    #[diagnostic(code(rust_curse::node::installed_cli_check_failed))]
    InstalledCliCheckFailed {
        #[source]
        source: CommandFailed,
    },
}

/// Errors that can happen while building native Node.js bindings.
#[derive(Error, Diagnostic, Debug)]
pub enum BuildError {
    #[error("failed to create NAPI CLI output directory at {}", path.display())]
    #[diagnostic(code(rust_curse::node::create_output_dir))]
    CreateOutputDir {
        path: PathBuf,
        #[source]
        source: std::io::Error,
    },

    #[error("failed to run NAPI CLI at {}", path.display())]
    #[diagnostic(code(rust_curse::node::run_napi_cli))]
    RunNapiCli {
        path: PathBuf,
        #[source]
        source: std::io::Error,
    },

    #[error("{source}")]
    #[diagnostic(code(rust_curse::node::napi_cli_failed))]
    NapiCliFailed {
        #[source]
        source: CommandFailed,
    },

    #[error("failed to read NAPI CLI output directory at {}", path.display())]
    #[diagnostic(code(rust_curse::node::read_output_dir))]
    ReadOutputDir {
        path: PathBuf,
        #[source]
        source: std::io::Error,
    },

    #[error("NAPI CLI did not generate expected JavaScript file at {}", path.display())]
    #[diagnostic(code(rust_curse::node::missing_generated_js))]
    MissingGeneratedJs { path: PathBuf },

    #[error("NAPI CLI did not generate a .node artifact in {}", out_dir_path.display())]
    #[diagnostic(code(rust_curse::node::missing_generated_node))]
    MissingGeneratedNode { out_dir_path: PathBuf },

    #[error("NAPI CLI generated multiple .node artifacts; expected exactly one\nartifacts:\n{artifacts}")]
    #[diagnostic(code(rust_curse::node::ambiguous_generated_node))]
    AmbiguousGeneratedNode { artifacts: String },
}
