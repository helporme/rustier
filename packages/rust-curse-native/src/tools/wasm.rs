//! Build Rust crates for wasm and run wasm-bindgen over the result.

use std::{
    fs,
    io::Cursor,
    path::{Path, PathBuf},
    process::{Command, Output},
};

use cargo_metadata::Message;
use miette::Diagnostic;
use thiserror::Error;
use tracing::{debug, info, trace};

const WASM_TARGET: &str = "wasm32-unknown-unknown";
const WASM_BINDGEN_PACKAGE: &str = "wasm-bindgen-cli";
const WASM_BINDGEN_BIN: &str = "wasm-bindgen";

/// Options for installing the local `wasm-bindgen` CLI tool.
pub struct EnsureWasmBindgenCliInstalledOpts<'a> {
    /// Directory passed to `cargo install --root`.
    pub install_root_path: &'a Path,
}

/// Options for building a crate for wasm and generating wasm-bindgen bindings.
pub struct BuildOpts<'a> {
    /// Crate directory used as the `cargo build` working directory.
    pub project_root_path: &'a Path,
    /// Directory where wasm-bindgen should write generated files.
    pub out_dir_path: &'a Path,
    /// Path to the local `wasm-bindgen` executable.
    pub wasm_bindgen_tool_bin_path: &'a Path,
    /// Whether to build with `cargo build --release`.
    pub release: bool,
    /// JavaScript runtime compatibility mode for generated bindings.
    pub compat: WasmCompat,
}

/// JavaScript runtime compatibility target passed to `wasm-bindgen --target`.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum WasmCompat {
    /// Generate bindings for Node.js.
    NodeJs,
    /// Generate bindings for browsers and bundlers.
    Web,
}

/// Files generated by `wasm-bindgen`.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct BuildOutput {
    /// Absolute path to the generated `_bg.wasm` file.
    pub wasm_abs_path: PathBuf,
    /// Absolute path to the generated JavaScript glue file.
    pub js_abs_path: PathBuf,
}

/// The expected path to the local `wasm-bindgen` binary.
#[tracing::instrument(level = "trace", skip_all, fields(install_root_path = %install_root_path.display()))]
pub fn wasm_bindgen_cli_path(install_root_path: &Path) -> PathBuf {
    let wasm_bindgen_bin_name = if std::env::consts::EXE_EXTENSION.is_empty() {
        WASM_BINDGEN_BIN.to_string()
    } else {
        format!("{WASM_BINDGEN_BIN}.{}", std::env::consts::EXE_EXTENSION)
    };

    let path = install_root_path.join("bin").join(wasm_bindgen_bin_name);
    trace!(path = %path.display(), "resolved wasm-bindgen CLI path");
    path
}

/// Ensure the `wasm32-unknown-unknown` Rust target is installed for the active
/// toolchain.
#[tracing::instrument(level = "debug")]
pub fn ensure_wasm_target_installed() -> Result<(), EnsureWasmTargetInstalledError> {
    debug!(target = WASM_TARGET, "checking installed Rust targets");

    let check = Command::new("rustup")
        .args(["target", "list", "--installed"])
        .output()
        .map_err(|source| EnsureWasmTargetInstalledError::CheckInstalledTargets { source })?;

    ensure_success(&check, "`rustup target list --installed` failed")
        .map_err(|source| EnsureWasmTargetInstalledError::ListInstalledTargetsFailed { source })?;

    let installed_targets = String::from_utf8_lossy(&check.stdout);
    if installed_targets
        .lines()
        .any(|line| line.trim() == WASM_TARGET)
    {
        debug!(target = WASM_TARGET, "Rust target is already installed");
        return Ok(());
    }

    info!(target = WASM_TARGET, "installing Rust target");

    let output = Command::new("rustup")
        .args(["target", "add", WASM_TARGET])
        .output()
        .map_err(|source| EnsureWasmTargetInstalledError::InstallTarget { source })?;

    ensure_success(
        &output,
        &format!("`rustup target add {WASM_TARGET}` failed"),
    )
    .map_err(|source| EnsureWasmTargetInstalledError::InstallTargetFailed { source })?;

    info!(target = WASM_TARGET, "installed Rust target");
    Ok(())
}

/// Ensure a local `wasm-bindgen` CLI is installed under `install_root_path`.
///
/// The absolute path to the installed `wasm-bindgen` binary.
///
/// ```no_run
/// use rust_curse::tools::wasm::{
///     ensure_wasm_bindgen_cli_installed, EnsureWasmBindgenCliInstalledOpts,
/// };
/// use std::path::Path;
///
/// let wasm_bindgen = ensure_wasm_bindgen_cli_installed(EnsureWasmBindgenCliInstalledOpts {
///     install_root_path: Path::new("/tmp/rust-curse-tools"),
/// })?;
/// # let _ = wasm_bindgen;
/// # Ok::<(), rust_curse::tools::wasm::EnsureWasmBindgenCliInstalledError>(())
/// ```
#[tracing::instrument(
    level = "debug",
    skip(opts),
    fields(install_root_path = %opts.install_root_path.display())
)]
pub fn ensure_wasm_bindgen_cli_installed(
    opts: EnsureWasmBindgenCliInstalledOpts<'_>,
) -> Result<PathBuf, EnsureWasmBindgenCliInstalledError> {
    debug!("ensuring wasm-bindgen CLI install root exists");

    fs::create_dir_all(opts.install_root_path).map_err(|source| {
        EnsureWasmBindgenCliInstalledError::CreateInstallRoot {
            path: opts.install_root_path.to_path_buf(),
            source,
        }
    })?;

    let tool_bin_abs_path = wasm_bindgen_cli_path(opts.install_root_path);
    let force_install = if tool_bin_abs_path.is_file() {
        debug!(path = %tool_bin_abs_path.display(), "checking existing wasm-bindgen CLI");

        let check = Command::new(&tool_bin_abs_path)
            .arg("--version")
            .output()
            .map_err(|source| EnsureWasmBindgenCliInstalledError::CheckCli {
                path: tool_bin_abs_path.clone(),
                source,
            })?;

        if check.status.success() {
            debug!(path = %tool_bin_abs_path.display(), "wasm-bindgen CLI is already installed");
            return Ok(tool_bin_abs_path);
        }

        debug!(path = %tool_bin_abs_path.display(), "existing wasm-bindgen CLI check failed; reinstalling");
        true
    } else {
        false
    };

    info!(
        package = WASM_BINDGEN_PACKAGE,
        install_root_path = %opts.install_root_path.display(),
        force_install,
        "installing wasm-bindgen CLI"
    );

    let mut install = Command::new("cargo");
    install.arg("install");
    if force_install {
        install.arg("--force");
    }
    install
        .arg(WASM_BINDGEN_PACKAGE)
        .arg("--root")
        .arg(opts.install_root_path);

    let output = install
        .output()
        .map_err(|source| EnsureWasmBindgenCliInstalledError::InstallCli { source })?;

    ensure_success(
        &output,
        &format!(
            "`cargo install {WASM_BINDGEN_PACKAGE} --root {}` failed",
            opts.install_root_path.display()
        ),
    )
    .map_err(|source| EnsureWasmBindgenCliInstalledError::InstallCliFailed { source })?;

    debug!(path = %tool_bin_abs_path.display(), "checking installed wasm-bindgen CLI");

    if !tool_bin_abs_path.is_file() {
        return Err(EnsureWasmBindgenCliInstalledError::MissingInstalledCli {
            path: tool_bin_abs_path,
        });
    }

    let check = Command::new(&tool_bin_abs_path)
        .arg("--version")
        .output()
        .map_err(|source| EnsureWasmBindgenCliInstalledError::CheckCli {
            path: tool_bin_abs_path.clone(),
            source,
        })?;

    ensure_success(
        &check,
        &format!(
            "installed wasm-bindgen CLI at {} failed `--version`",
            tool_bin_abs_path.display()
        ),
    )
    .map_err(|source| EnsureWasmBindgenCliInstalledError::InstalledCliCheckFailed { source })?;

    info!(path = %tool_bin_abs_path.display(), "installed wasm-bindgen CLI");

    Ok(tool_bin_abs_path)
}

/// Build a crate for wasm and run `wasm-bindgen` to generate JavaScript
/// bindings.
///
/// `project_root_path` is used as the working directory for `cargo build`. The
/// build must produce exactly one `.wasm` artifact.
///
/// ```no_run
/// use rust_curse::tools::wasm::{build, BuildOpts, WasmCompat};
/// use std::path::Path;
///
/// let output = build(BuildOpts {
///     project_root_path: Path::new("/path/to/crate"),
///     out_dir_path: Path::new("/path/to/out"),
///     wasm_bindgen_tool_bin_path: Path::new("/path/to/wasm-bindgen"),
///     release: true,
///     compat: WasmCompat::Web,
/// })?;
/// # let _ = output;
/// # Ok::<(), rust_curse::tools::wasm::BuildError>(())
/// ```
#[tracing::instrument(
    level = "debug",
    skip(opts),
    fields(
        project_root_path = %opts.project_root_path.display(),
        out_dir_path = %opts.out_dir_path.display(),
        wasm_bindgen_tool_bin_path = %opts.wasm_bindgen_tool_bin_path.display(),
        release = opts.release,
        compat = ?opts.compat,
    )
)]
pub fn build(opts: BuildOpts<'_>) -> Result<BuildOutput, BuildError> {
    info!("building wasm profile crate");

    let mut build = Command::new("cargo");
    build
        .arg("build")
        .arg("--target")
        .arg(WASM_TARGET)
        .arg("--message-format=json-render-diagnostics")
        .current_dir(opts.project_root_path);
    if opts.release {
        build.arg("--release");
    }

    debug!(
        target = WASM_TARGET,
        current_dir = %opts.project_root_path.display(),
        release = opts.release,
        "running cargo build for wasm"
    );

    let output = build
        .output()
        .map_err(|source| BuildError::RunCargoBuild { source })?;

    ensure_success(
        &output,
        &format!(
            "`cargo build --target {WASM_TARGET}` failed in {}",
            opts.project_root_path.display()
        ),
    )
    .map_err(|source| BuildError::CargoBuildFailed { source })?;

    let built_wasm_abs_path = built_wasm_artifact(&output, opts.project_root_path)?;
    debug!(path = %built_wasm_abs_path.display(), "found built wasm artifact");

    debug!(path = %opts.out_dir_path.display(), "ensuring wasm-bindgen output directory exists");
    fs::create_dir_all(opts.out_dir_path).map_err(|source| BuildError::CreateOutputDir {
        path: opts.out_dir_path.to_path_buf(),
        source,
    })?;

    let out_name = built_wasm_abs_path
        .file_stem()
        .and_then(|stem| stem.to_str())
        .ok_or_else(|| BuildError::MissingWasmFileStem {
            path: built_wasm_abs_path.clone(),
        })?;
    let wasm_bindgen_target = match opts.compat {
        WasmCompat::NodeJs => "nodejs",
        WasmCompat::Web => "web",
    };

    debug!(
        path = %opts.wasm_bindgen_tool_bin_path.display(),
        input = %built_wasm_abs_path.display(),
        out_dir = %opts.out_dir_path.display(),
        target = wasm_bindgen_target,
        out_name,
        "running wasm-bindgen"
    );

    let bindgen = Command::new(opts.wasm_bindgen_tool_bin_path)
        .arg(&built_wasm_abs_path)
        .arg("--out-dir")
        .arg(opts.out_dir_path)
        .arg("--target")
        .arg(wasm_bindgen_target)
        .arg("--out-name")
        .arg(out_name)
        .output()
        .map_err(|source| BuildError::RunWasmBindgenCli {
            path: opts.wasm_bindgen_tool_bin_path.to_path_buf(),
            source,
        })?;

    ensure_success(
        &bindgen,
        &format!(
            "`{}` failed for {}",
            opts.wasm_bindgen_tool_bin_path.display(),
            built_wasm_abs_path.display()
        ),
    )
    .map_err(|source| BuildError::WasmBindgenCliFailed { source })?;

    let js_abs_path = opts.out_dir_path.join(format!("{out_name}.js"));
    let wasm_abs_path = opts.out_dir_path.join(format!("{out_name}_bg.wasm"));

    if !js_abs_path.is_file() {
        return Err(BuildError::MissingGeneratedJs { path: js_abs_path });
    }

    if !wasm_abs_path.is_file() {
        return Err(BuildError::MissingGeneratedWasm {
            path: wasm_abs_path,
        });
    }

    info!(
        js_abs_path = %js_abs_path.display(),
        wasm_abs_path = %wasm_abs_path.display(),
        "built wasm profile crate"
    );

    Ok(BuildOutput {
        wasm_abs_path,
        js_abs_path,
    })
}

#[tracing::instrument(level = "trace", skip(output), fields(project_root_abs_path = %project_root_abs_path.display()))]
fn built_wasm_artifact(
    output: &Output,
    project_root_abs_path: &Path,
) -> Result<PathBuf, BuildError> {
    let mut wasm_paths = Vec::new();

    for message in Message::parse_stream(Cursor::new(&output.stdout)) {
        let message = message.map_err(|source| BuildError::ParseCargoBuildMessage { source })?;
        let Message::CompilerArtifact(artifact) = message else {
            continue;
        };

        for filename in artifact.filenames {
            let path = filename.into_std_path_buf();
            if path.extension().and_then(|ext| ext.to_str()) == Some("wasm") {
                trace!(path = %path.display(), "found wasm artifact candidate");
                wasm_paths.push(path);
            }
        }
    }

    match wasm_paths.len() {
        0 => Err(BuildError::MissingBuiltWasm {
            project_root_abs_path: project_root_abs_path.to_path_buf(),
        }),
        1 => Ok(wasm_paths.remove(0)),
        _ => {
            let artifacts = wasm_paths
                .iter()
                .map(|path| format!("  - {}", path.display()))
                .collect::<Vec<_>>()
                .join("\n");
            Err(BuildError::AmbiguousBuiltWasm { artifacts })
        }
    }
}

fn ensure_success(output: &Output, context: &str) -> Result<(), CommandFailed> {
    if output.status.success() {
        return Ok(());
    }

    Err(CommandFailed {
        context: context.to_string(),
        exit_code: output.status.code(),
        stdout: String::from_utf8_lossy(&output.stdout)
            .trim_end()
            .to_string(),
        stderr: String::from_utf8_lossy(&output.stderr)
            .trim_end()
            .to_string(),
    })
}

#[derive(Error, Diagnostic, Debug)]
#[error("{context} (exit code {exit_code:?})\nstdout:\n{stdout}\nstderr:\n{stderr}")]
#[diagnostic(code(rust_curse::wasm::command_failed))]
pub struct CommandFailed {
    context: String,
    exit_code: Option<i32>,
    stdout: String,
    stderr: String,
}

#[derive(Error, Diagnostic, Debug)]
pub enum EnsureWasmTargetInstalledError {
    #[error("failed to run `rustup target list --installed`; is rustup installed?")]
    #[diagnostic(code(rust_curse::wasm::check_installed_targets))]
    CheckInstalledTargets {
        #[source]
        source: std::io::Error,
    },

    #[error("{source}")]
    #[diagnostic(code(rust_curse::wasm::list_installed_targets_failed))]
    ListInstalledTargetsFailed {
        #[source]
        source: CommandFailed,
    },

    #[error("failed to run `rustup target add {WASM_TARGET}`")]
    #[diagnostic(code(rust_curse::wasm::install_target))]
    InstallTarget {
        #[source]
        source: std::io::Error,
    },

    #[error("{source}")]
    #[diagnostic(code(rust_curse::wasm::install_target_failed))]
    InstallTargetFailed {
        #[source]
        source: CommandFailed,
    },
}

#[derive(Error, Diagnostic, Debug)]
pub enum EnsureWasmBindgenCliInstalledError {
    #[error("failed to create wasm-bindgen install root at {}", path.display())]
    #[diagnostic(code(rust_curse::wasm::create_install_root))]
    CreateInstallRoot {
        path: PathBuf,
        #[source]
        source: std::io::Error,
    },

    #[error("failed to run wasm-bindgen CLI at {}", path.display())]
    #[diagnostic(code(rust_curse::wasm::check_cli))]
    CheckCli {
        path: PathBuf,
        #[source]
        source: std::io::Error,
    },

    #[error("failed to run `cargo install {WASM_BINDGEN_PACKAGE}`")]
    #[diagnostic(code(rust_curse::wasm::install_cli))]
    InstallCli {
        #[source]
        source: std::io::Error,
    },

    #[error("{source}")]
    #[diagnostic(code(rust_curse::wasm::install_cli_failed))]
    InstallCliFailed {
        #[source]
        source: CommandFailed,
    },

    #[error("`cargo install {WASM_BINDGEN_PACKAGE}` completed but did not create {}", path.display())]
    #[diagnostic(code(rust_curse::wasm::missing_installed_cli))]
    MissingInstalledCli { path: PathBuf },

    #[error("{source}")]
    #[diagnostic(code(rust_curse::wasm::installed_cli_check_failed))]
    InstalledCliCheckFailed {
        #[source]
        source: CommandFailed,
    },
}

#[derive(Error, Diagnostic, Debug)]
pub enum BuildError {
    #[error("failed to run `cargo build --target {WASM_TARGET}`")]
    #[diagnostic(code(rust_curse::wasm::run_cargo_build))]
    RunCargoBuild {
        #[source]
        source: std::io::Error,
    },

    #[error("{source}")]
    #[diagnostic(code(rust_curse::wasm::cargo_build_failed))]
    CargoBuildFailed {
        #[source]
        source: CommandFailed,
    },

    #[error("failed to parse cargo build JSON messages")]
    #[diagnostic(code(rust_curse::wasm::parse_cargo_build_message))]
    ParseCargoBuildMessage {
        #[source]
        source: std::io::Error,
    },

    #[error("cargo build in {} did not produce a .wasm artifact", project_root_abs_path.display())]
    #[diagnostic(code(rust_curse::wasm::missing_built_wasm))]
    MissingBuiltWasm { project_root_abs_path: PathBuf },

    #[error(
        "cargo build produced multiple .wasm artifacts; expected exactly one\nartifacts:\n{artifacts}"
    )]
    #[diagnostic(code(rust_curse::wasm::ambiguous_built_wasm))]
    AmbiguousBuiltWasm { artifacts: String },

    #[error("failed to create wasm-bindgen output directory at {}", path.display())]
    #[diagnostic(code(rust_curse::wasm::create_output_dir))]
    CreateOutputDir {
        path: PathBuf,
        #[source]
        source: std::io::Error,
    },

    #[error("built wasm artifact path has no valid UTF-8 file stem: {}", path.display())]
    #[diagnostic(code(rust_curse::wasm::missing_wasm_file_stem))]
    MissingWasmFileStem { path: PathBuf },

    #[error("failed to run wasm-bindgen CLI at {}", path.display())]
    #[diagnostic(code(rust_curse::wasm::run_wasm_bindgen_cli))]
    RunWasmBindgenCli {
        path: PathBuf,
        #[source]
        source: std::io::Error,
    },

    #[error("{source}")]
    #[diagnostic(code(rust_curse::wasm::wasm_bindgen_cli_failed))]
    WasmBindgenCliFailed {
        #[source]
        source: CommandFailed,
    },

    #[error("wasm-bindgen did not generate expected JavaScript file at {}", path.display())]
    #[diagnostic(code(rust_curse::wasm::missing_generated_js))]
    MissingGeneratedJs { path: PathBuf },

    #[error("wasm-bindgen did not generate expected wasm file at {}", path.display())]
    #[diagnostic(code(rust_curse::wasm::missing_generated_wasm))]
    MissingGeneratedWasm { path: PathBuf },
}
