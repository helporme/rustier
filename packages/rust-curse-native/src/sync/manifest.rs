//! Manifest rendering for generated cursed crates.

use std::path::Path;

use crate::compiler::Platform;

pub struct ManifestOpts<'a> {
    pub name: &'a str,
    pub version: &'a str,
    pub edition: &'a str,
    pub source_crate_name: &'a str,
    pub source_package_path: &'a Path,
}

pub fn render_manifest(platform: Platform, opts: ManifestOpts<'_>) -> String {
    let build = matches!(platform, Platform::Node)
        .then_some("build = \"build.rs\"\n")
        .unwrap_or_default();
    let dependencies = match platform {
        Platform::Wasm { .. } => "wasm-bindgen = \"0.2\"\n",
        Platform::Node => {
            "napi = { version = \"3\", features = [\"napi10\"] }\n\
             napi-derive = \"3\"\n"
        }
    };
    let build_dependencies = matches!(platform, Platform::Node)
        .then_some("\n[build-dependencies]\nnapi-build = \"2\"\n")
        .unwrap_or_default();

    format!(
        "# @generated by rust-curse. Do not edit manually.\n\n\
         [package]\n\
         name = {}\n\
         version = {}\n\
         edition = {}\n\
         publish = false\n\
         {build}\n\
         [lib]\n\
         crate-type = [\"cdylib\", \"rlib\"]\n\n\
         [dependencies]\n\
         {} = {{ package = {}, path = {} }}\n\
         {dependencies}{build_dependencies}",
        toml_string(&format!("cursed-{}", opts.name)),
        toml_string(opts.version),
        toml_string(opts.edition),
        toml_string(opts.source_crate_name),
        toml_string(opts.name),
        toml_string(opts.source_package_path.to_string_lossy().as_ref()),
    )
}

fn toml_string(value: &str) -> String {
    format!("\"{}\"", value.replace('\\', "\\\\").replace('"', "\\\""))
}
