//! Manifest rendering for generated cursed crates.

use std::path::Path;

use indoc::indoc;

use crate::compiler::{codegen::fragment::FragmentPrint, db::Db, inputs::Platform};

/// Options used to render `Cargo.toml` contents for the generated cursed crate.
pub struct ManifestOpts<'a> {
    /// The source package name used in the generated dependency declaration.
    pub name: &'a str,
    /// The generated cursed package version.
    pub version: &'a str,
    /// The Rust edition used by the generated cursed package.
    pub edition: &'a str,
    /// The source crate name used as the dependency key.
    pub source_crate_name: &'a str,
    /// The filesystem path to the source package.
    pub source_package_path: &'a Path,
}

/// Renders `Cargo.toml` contents for the generated cursed crate.
///
/// # Example
///
/// ```
/// use rust_curse::{
///     compiler::{
///         db::RootDatabase,
///         inputs::{Platform, WasmEnv},
///     },
///     sync::manifest::{ManifestOpts, render_manifest},
/// };
///
/// let mut db = RootDatabase::default();
/// Platform::set(
///     &mut db,
///     Platform::Wasm {
///         target: WasmEnv::Web,
///     },
/// );
///
/// let manifest = render_manifest(
///     &db,
///     ManifestOpts {
///         name: "demo-crate",
///         version: "1.2.3",
///         edition: "2021",
///         source_crate_name: "demo_crate",
///         source_package_path: std::path::Path::new("/workspace/demo-crate"),
///     },
/// );
///
/// assert!(manifest.contains("name = \"cursed-demo-crate\""));
/// assert!(manifest.contains("wasm-bindgen = \"0.2\""));
/// ```
pub fn render_manifest(db: &dyn Db, opts: ManifestOpts<'_>) -> String {
    let package_name = toml_string(opts.name);
    let cursed_package_name = toml_string(&format!("cursed-{}", opts.name));
    let version = toml_string(opts.version);
    let edition = toml_string(opts.edition);
    let source_crate_name = toml_string(opts.source_crate_name);
    let source_package_path = opts.source_package_path.to_string_lossy();
    let source_package_path = toml_string(source_package_path.as_ref());

    let platform = Platform::get(db);
    let package_build = if platform.needs_build_script() {
        indoc! {r#"
            build = "build.rs"
        "#}
    } else {
        ""
    };
    let platform_dependencies = platform.manifest_deps().print();
    let platform_build_dependencies = platform.manifest_build_deps().print();
    let should_end_with_newline = platform_build_dependencies.is_empty();

    let mut manifest = format!(
        indoc! {r#"
            # @generated by rust-curse. Do not edit manually.

            [package]
            name = {cursed_package_name}
            version = {version}
            edition = {edition}
            publish = false
            {package_build}
            [lib]
            crate-type = ["cdylib", "rlib"]

            [dependencies]
            {source_crate_name} = {{ package = {package_name}, path = {source_package_path} }}
            {platform_dependencies}{platform_build_dependencies}"#
        },
        platform_build_dependencies = platform_build_dependencies,
        platform_dependencies = platform_dependencies,
        cursed_package_name = cursed_package_name,
        edition = edition,
        package_build = package_build,
        package_name = package_name,
        source_crate_name = source_crate_name,
        source_package_path = source_package_path,
        version = version,
    );

    if should_end_with_newline {
        manifest.push('\n');
    }

    manifest
}

fn toml_string(value: &str) -> String {
    format!("\"{}\"", escape_toml(value))
}

fn escape_toml(value: &str) -> String {
    value.replace('\\', "\\\\").replace('"', "\\\"")
}

#[cfg(test)]
mod tests {
    use crate::compiler::{
        db::RootDatabase,
        inputs::{Platform, WasmEnv},
    };

    use super::*;

    #[test]
    fn renders_wasm_manifest() {
        assert_eq!(
            render_manifest(&db(wasm_platform()), package_opts("demo_crate")),
            indoc! {r#"
                # @generated by rust-curse. Do not edit manually.

                [package]
                name = "cursed-demo-crate"
                version = "1.2.3"
                edition = "2021"
                publish = false

                [lib]
                crate-type = ["cdylib", "rlib"]

                [dependencies]
                "demo_crate" = { package = "demo-crate", path = "/workspace/demo-crate" }
                wasm-bindgen = "0.2"
            "#},
        );
    }

    #[test]
    fn renders_node_manifest() {
        assert_eq!(
            render_manifest(&db(Platform::Node), package_opts("demo_crate")),
            indoc! {r#"
                # @generated by rust-curse. Do not edit manually.

                [package]
                name = "cursed-demo-crate"
                version = "1.2.3"
                edition = "2021"
                publish = false
                build = "build.rs"

                [lib]
                crate-type = ["cdylib", "rlib"]

                [dependencies]
                "demo_crate" = { package = "demo-crate", path = "/workspace/demo-crate" }
                napi = { version = "3", features = ["napi10"] }
                napi-derive = { version = "3" }

                [build-dependencies]
                napi-build = "2""#},
        );
    }

    #[test]
    fn uses_custom_library_target_as_dependency_key() {
        assert_eq!(
            render_manifest(&db(wasm_platform()), package_opts("demo_bindings")),
            indoc! {r#"
                # @generated by rust-curse. Do not edit manually.

                [package]
                name = "cursed-demo-crate"
                version = "1.2.3"
                edition = "2021"
                publish = false

                [lib]
                crate-type = ["cdylib", "rlib"]

                [dependencies]
                "demo_bindings" = { package = "demo-crate", path = "/workspace/demo-crate" }
                wasm-bindgen = "0.2"
            "#},
        );
    }

    fn wasm_platform() -> Platform {
        Platform::Wasm {
            target: WasmEnv::Web,
        }
    }

    fn db(platform: Platform) -> RootDatabase {
        let mut db = RootDatabase::default();
        Platform::set(&mut db, platform);
        db
    }

    fn package_opts(source_crate_name: &str) -> ManifestOpts<'_> {
        ManifestOpts {
            name: "demo-crate",
            version: "1.2.3",
            edition: "2021",
            source_crate_name,
            source_package_path: Path::new("/workspace/demo-crate"),
        }
    }
}
