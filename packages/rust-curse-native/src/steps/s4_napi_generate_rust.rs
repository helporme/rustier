//! Step 4 for NAPI target.
//! Generates lib.rs with NAPI bindings, a module scaffold linking to original
//! source files, and patches Cargo.toml for NAPI builds.

use std::collections::BTreeMap;
use std::fmt::Write;
use std::fs;
use std::path::Path;

use toml_edit::DocumentMut;

use crate::steps::{
    s1_discovery::{RustModule, RustModuleFn, RustModuleMember},
    s3_treeshake::RustModuleShaked,
};

/// Generates `lib.rs`, module scaffold, and NAPI glue for all shaked modules.
pub fn generate_lib_and_modules(
    output_dir: &Path,
    all_modules: &[RustModule],
    shaked: &[RustModuleShaked],
) {
    let mut tree = ModTree::default();
    for module in all_modules {
        tree.insert(&module.name, &module.path);
    }

    // Generate lib.rs
    let mut lib_rs = String::from(
        "// Auto-generated by rust-curse.\n\n\
         #![allow(warnings)]\n\n\
         use napi_derive::napi;\n\
         use napi::bindgen_prelude::*;\n\
         use napi::sys;\n\
         use serde::{Serialize, Deserialize, de::DeserializeOwned};\n\n\
         pub struct Packed<T>(pub T);\n\n\
         impl<T: DeserializeOwned> FromNapiValue for Packed<T> {\n\
         \x20   unsafe fn from_napi_value(env: sys::napi_env, napi_val: sys::napi_value) -> Result<Self> {\n\
         \x20       let json = unsafe {\n\
         \x20           <serde_json::Value as FromNapiValue>::from_napi_value(env, napi_val)?\n\
         \x20       };\n\
         \x20       serde_json::from_value(json)\n\
         \x20           .map(Packed)\n\
         \x20           .map_err(|e| napi::Error::from_reason(e.to_string()))\n\
         \x20   }\n\
         }\n\n\
         impl<T: Serialize> ToNapiValue for Packed<T> {\n\
         \x20   unsafe fn to_napi_value(env: sys::napi_env, val: Self) -> Result<sys::napi_value> {\n\
         \x20       let json = serde_json::to_value(&val.0)\n\
         \x20           .map_err(|e| napi::Error::from_reason(e.to_string()))?;\n\
         \x20       unsafe { <serde_json::Value as ToNapiValue>::to_napi_value(env, json) }\n\
         \x20   }\n\
         }\n\n",
    );

    for (name, child) in &tree.children {
        if child.children.is_empty() {
            if let Some(ref path) = child.file_path {
                writeln!(lib_rs, "#[path = {:?}]", path).unwrap();
            }
        }
        writeln!(lib_rs, "pub(crate) mod {};", name).unwrap();
    }
    writeln!(lib_rs).unwrap();

    // Generate NAPI glue for each shaked module's imported members
    for s in shaked {
        if let Some(ref members) = s.module.members {
            write_napi_glue_for_members(&mut lib_rs, members, &s.imported_members);
        }
    }

    fs::create_dir_all(output_dir).expect("failed to create output directory");
    fs::write(output_dir.join("lib.rs"), &lib_rs).expect("failed to write lib.rs");

    // Generate build.rs for napi-build
    fs::write(
        output_dir.join("build.rs"),
        "extern crate napi_build;\n\nfn main() {\n    napi_build::setup();\n}\n",
    )
    .expect("failed to write build.rs");

    // Generate module scaffold (same as dev target)
    for (name, child) in &tree.children {
        if !child.children.is_empty() {
            let dir = output_dir.join(name);
            fs::create_dir_all(&dir).expect("failed to create module directory");
            write_mod_file(child, &dir);
        }
    }
}

fn write_napi_glue_for_members(
    out: &mut String,
    members: &[RustModuleMember],
    imported: &[String],
) {
    for member in members {
        match member {
            RustModuleMember::Fn(func) => {
                let short = func.name.rsplit("::").next().unwrap_or(&func.name);
                if imported.contains(&short.to_string()) || imported.contains(&"*".to_string()) {
                    generate_fn_glue(out, &func.name, func);
                }
            }
            RustModuleMember::Module(sub) => {
                // For sub-modules imported as a member (e.g. `import { messages } from './hello'`),
                // generate glue for all their public functions
                let short = sub.name.rsplit("::").next().unwrap_or(&sub.name);
                if imported.contains(&short.to_string()) || imported.contains(&"*".to_string()) {
                    if let Some(ref sub_members) = sub.members {
                        write_napi_glue_all(out, &sub.name, sub_members);
                    }
                }
            }
        }
    }
}

/// Generates NAPI glue for all functions in a module tree (used for sub-module imports).
fn write_napi_glue_all(out: &mut String, _parent_name: &str, members: &[RustModuleMember]) {
    for member in members {
        match member {
            RustModuleMember::Fn(func) => {
                generate_fn_glue(out, &func.name, func);
            }
            RustModuleMember::Module(sub) => {
                if let Some(ref sub_members) = sub.members {
                    write_napi_glue_all(out, &sub.name, sub_members);
                }
            }
        }
    }
}

fn generate_fn_glue(out: &mut String, full_name: &str, func: &RustModuleFn) {
    // Convert foo::bar::fn_name to foo__bar__fn_name
    let napi_name = full_name.replace("::", "__");
    let call_path = full_name; // e.g. routes::greeting::greet

    let has_args = !func.args.is_empty();
    let has_return = !func.return_type_name.is_empty();

    // Generate args struct if needed
    let struct_name = format!("{}__Args", napi_name);
    if has_args {
        writeln!(out, "#[derive(Serialize, Deserialize)]").unwrap();
        writeln!(out, "pub struct {} {{", struct_name).unwrap();
        for arg in &func.args {
            writeln!(out, "    pub {}: {},", arg.name, arg.type_name).unwrap();
        }
        writeln!(out, "}}").unwrap();
        writeln!(out).unwrap();
    }

    let return_sig = if has_return {
        format!(" -> Packed<{}>", func.return_type_name)
    } else {
        String::new()
    };

    let param_sig = if has_args {
        format!("args: Packed<{}>", struct_name)
    } else {
        String::new()
    };

    writeln!(out, "#[napi]").unwrap();
    writeln!(out, "pub fn {}({}){} {{", napi_name, param_sig, return_sig).unwrap();

    let call_args: Vec<String> = func
        .args
        .iter()
        .map(|a| format!("args.0.{}", a.name))
        .collect();
    let call_expr = format!("{}({})", call_path, call_args.join(", "));

    if has_return {
        writeln!(out, "    Packed({})", call_expr).unwrap();
    } else {
        writeln!(out, "    {}", call_expr).unwrap();
    }
    writeln!(out, "}}").unwrap();
    writeln!(out).unwrap();
}

fn write_mod_file(node: &ModTree, dir: &Path) {
    let mut content = String::new();

    for (name, child) in &node.children {
        if child.children.is_empty() {
            if let Some(ref path) = child.file_path {
                writeln!(content, "#[path = {:?}]", path).unwrap();
            }
            writeln!(content, "pub(crate) mod {};", name).unwrap();
        } else {
            writeln!(content, "pub(crate) mod {};", name).unwrap();
            let subdir = dir.join(name);
            fs::create_dir_all(&subdir).expect("failed to create module directory");
            write_mod_file(child, &subdir);
        }
    }

    if let Some(ref path) = node.file_path {
        writeln!(content, "include!({:?});", path).unwrap();
    }

    fs::write(dir.join("mod.rs"), &content).expect("failed to write mod.rs");
}

#[derive(Default)]
struct ModTree {
    file_path: Option<String>,
    children: BTreeMap<String, ModTree>,
}

impl ModTree {
    fn insert(&mut self, module_name: &str, file_path: &str) {
        let segments: Vec<&str> = module_name.split("::").collect();
        let mut node = self;
        for (i, seg) in segments.iter().enumerate() {
            node = node.children.entry(seg.to_string()).or_default();
            if i == segments.len() - 1 {
                node.file_path = Some(file_path.to_string());
            }
        }
    }
}

/// Patches an existing Cargo.toml to be buildable with NAPI.
pub fn generate_cargo_toml(mut doc: DocumentMut, lib_rs_path: &str) -> DocumentMut {
    let lib = doc["lib"].or_insert(toml_edit::Item::Table(toml_edit::Table::new()));
    let lib_table = lib.as_table_mut().expect("[lib] should be a table");

    lib_table.insert(
        "crate-type",
        toml_edit::value(toml_edit::Array::from_iter(["cdylib"])),
    );
    lib_table.insert("path", toml_edit::value(lib_rs_path));

    ensure_dep(&mut doc, "dependencies", "napi", || {
        let mut t = toml_edit::InlineTable::new();
        t.insert("version", "3".into());
        t.insert("default-features", false.into());
        let mut features = toml_edit::Array::new();
        features.push("napi6");
        features.push("serde-json");
        t.insert("features", toml_edit::Value::Array(features));
        toml_edit::Item::Value(toml_edit::Value::InlineTable(t))
    });
    ensure_dep(&mut doc, "dependencies", "napi-derive", || {
        let mut t = toml_edit::InlineTable::new();
        t.insert("version", "3".into());
        let mut features = toml_edit::Array::new();
        features.push("type-def");
        t.insert("features", toml_edit::Value::Array(features));
        toml_edit::Item::Value(toml_edit::Value::InlineTable(t))
    });
    ensure_dep(&mut doc, "build-dependencies", "napi-build", || {
        toml_edit::value("2")
    });
    ensure_dep(&mut doc, "dependencies", "serde", || {
        let mut t = toml_edit::InlineTable::new();
        t.insert("version", "1".into());
        let mut features = toml_edit::Array::new();
        features.push("derive");
        t.insert("features", toml_edit::Value::Array(features));
        toml_edit::Item::Value(toml_edit::Value::InlineTable(t))
    });
    ensure_dep(&mut doc, "dependencies", "serde_json", || {
        toml_edit::value("1")
    });

    doc
}

fn ensure_dep(
    doc: &mut DocumentMut,
    section: &str,
    name: &str,
    make: impl FnOnce() -> toml_edit::Item,
) {
    let deps = doc[section].or_insert(toml_edit::Item::Table(toml_edit::Table::new()));
    let deps_table = deps.as_table_mut().expect("deps section should be a table");
    if !deps_table.contains_key(name) {
        deps_table.insert(name, make());
    }
}
