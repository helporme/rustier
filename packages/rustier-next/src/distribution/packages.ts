import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { dirname, relative, resolve } from 'node:path'
import { spawnSync } from 'node:child_process'
import { applyEdits, modify } from 'jsonc-parser'

import type { DistributionPlan, PackageMetadata } from './plan'
import publishScript from './publish.js?raw'
import { npmSetupWarnings, type SetupMetadata } from './setup'

export function readPackageMetadata(root: string): PackageMetadata {
  return JSON.parse(readFileSync(resolve(root, 'package.json'), 'utf8'))
}

function patchRootManifest(path: string, name: string, version: string, packageDir: string): SetupMetadata {
  const source = readFileSync(path, 'utf8')
  const metadata: SetupMetadata = JSON.parse(source)
  if (metadata.version !== version) throw new Error('Root version changed during the build; rebuild before packaging')

  const indent = source.match(/\n([ \t]+)"/)?.[1]
  const formattingOptions = source.includes('\n') ? {
    insertSpaces: !indent?.includes('\t'),
    tabSize: indent?.length ?? 2,
    eol: source.includes('\r\n') ? '\r\n' : '\n',
  } : undefined
  let updated = source
  function set(key: string[], value: string) {
    updated = applyEdits(updated, modify(updated, key, value, { formattingOptions }))
  }

  if (metadata.dependencies?.[name] !== version) set(['dependencies', name], version)
  if (metadata.scripts?.prepublishOnly === undefined) {
    set(['scripts', 'prepublishOnly'], `node ./${packageDir}/publish.mjs`)
  }
  if (updated !== source) writeFileSync(path, updated)
  return JSON.parse(updated)
}

export function writePackages(root: string, plan: DistributionPlan, patchPackageJson: boolean): string[] {
  if (plan.entry.type !== 'package' || !plan.packageDir) throw new Error('Expected an npm distribution plan')

  const rootManifest = resolve(root, 'package.json')
  let metadata: SetupMetadata = JSON.parse(readFileSync(rootManifest, 'utf8'))

  for (const pkg of plan.packages) {
    const manifest = JSON.parse(pkg.files.find(file => file.path === 'package.json')!.contents as string)
    if (manifest.version !== metadata.version) throw new Error('Root version changed during the build; rebuild before packaging')
  }

  const packageDir = resolve(root, plan.packageDir)
  mkdirSync(packageDir, { recursive: true })

  const cli = process.env.npm_execpath
  // Use npm only to compute tarball integrity. This never publishes or runs lifecycle scripts.
  const npmArgs = cli && /npm-cli\.js$/.test(cli) ? [process.execPath, [cli]] as const : ['npm', []] as const
  const pack = (directory: string): { integrity: string, files: { path: string }[] } => {
    const packed = spawnSync(npmArgs[0], [...npmArgs[1], 'pack', '--dry-run', '--json', '--ignore-scripts'], {
      cwd: directory, encoding: 'utf8', shell: process.platform === 'win32' && npmArgs[0] === 'npm',
    })
    if (packed.error) throw packed.error
    if (packed.status !== 0) throw new Error(packed.stderr || packed.stdout || 'npm pack failed')

    return JSON.parse(packed.stdout)[0]
  }

  const entries = []

  for (const pkg of plan.packages) {
    const directory = resolve(packageDir, pkg.directory)
    const manifest = resolve(directory, 'package.json')

    if (existsSync(directory) && readdirSync(directory).length
      && (!existsSync(manifest) || !JSON.parse(readFileSync(manifest, 'utf8')).rustierGenerated)) {
      throw new Error(`Refusing to overwrite a non-generated package at ${directory}`)
    }

    mkdirSync(directory, { recursive: true })
    for (const file of [...pkg.files].sort((a, b) => Number(b.path === 'package.json') - Number(a.path === 'package.json'))) {
      const path = resolve(directory, file.path)
      mkdirSync(dirname(path), { recursive: true })
      writeFileSync(path, file.contents)
    }

    const result = pack(directory)
    entries.push({ name: pkg.name, directory: pkg.directory, integrity: result.integrity })
  }

  const script = resolve(packageDir, 'publish.mjs')
  if (existsSync(script) && !readFileSync(script, 'utf8').startsWith('// Generated by Rustier.')) {
    throw new Error(`Refusing to overwrite ${script}`)
  }

  writeFileSync(script, publishScript)
  writeFileSync(resolve(packageDir, 'packages.json'), JSON.stringify({
    root: relative(packageDir, root) || '.',
    packageDir: plan.packageDir,
    version: metadata.version,
    packages: entries,
  }, null, 2) + '\n')

  if (patchPackageJson) {
    metadata = patchRootManifest(rootManifest, plan.entry.specifier, metadata.version, plan.packageDir)
  }

  try {
    return npmSetupWarnings(metadata, plan, pack(root).files.map(file => file.path))
  } catch (error) {
    return [
      ...npmSetupWarnings(metadata, plan),
      `Could not check the root tarball: ${String(error)}\n`
      + `Run npm pack --dry-run --ignore-scripts from the root. Fix any pack error, then check that no ${plan.packageDir}/ files are listed.`,
    ]
  }
}
